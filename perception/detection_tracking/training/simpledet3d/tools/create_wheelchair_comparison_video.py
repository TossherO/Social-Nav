#!/usr/bin/env python3
"""Create a full-sequence GT / one-frame / four-frame BEV comparison MP4.

Predictions must first be generated by ``visualize_wheelchair_predictions.py``.
This keeps GPU inference separate from CPU rendering and makes the exact model
outputs used by the video auditable and reusable.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import numpy as np
from tqdm import tqdm


PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from tools.compare_wheelchair_predictions import (  # noqa: E402
    _plot_common_background,
    _plot_predictions,
    load_predictions,
)
from tools.visualize_wheelchair_predictions import (  # noqa: E402
    _manual_centers_in_range,
    _plot_box,
    _plot_point_subsets,
    _weak_overlays,
    greedy_center_matches,
)


DEFAULT_CFG = 'configs/voxelrcnn_wheelchair_weak_stage3.yaml'
DEFAULT_SINGLE_PREDICTIONS = (
    'output/wheelchair_sequence_video/'
    'sequence4_003_single_inference/predictions.pkl'
)
DEFAULT_FOUR_PREDICTIONS = (
    'output/wheelchair_sequence_video/'
    'sequence4_003_four_inference/predictions.pkl'
)
DEFAULT_OUTPUT_FILE = (
    'output/wheelchair_sequence_video/'
    'indoor2_sequence4_003_1frame_vs_4frame.mp4'
)


def parse_args():
    parser = argparse.ArgumentParser(
        description='Create a full-sequence three-panel Wheelchair BEV MP4',
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument('--cfg_file', default=DEFAULT_CFG)
    parser.add_argument('--single_predictions', default=DEFAULT_SINGLE_PREDICTIONS)
    parser.add_argument('--four_predictions', default=DEFAULT_FOUR_PREDICTIONS)
    parser.add_argument('--output_file', default=DEFAULT_OUTPUT_FILE)
    parser.add_argument('--root_path', default=None)
    parser.add_argument('--raw_data_path', default=None)
    parser.add_argument('--info_path', nargs='+', default=None)
    parser.add_argument('--fps', type=float, default=10.0)
    parser.add_argument('--score_thresh', type=float, default=0.3)
    parser.add_argument('--match_radius', type=float, default=0.5)
    parser.add_argument('--min_box_points', type=int, default=3)
    parser.add_argument('--max_points', type=int, default=30000)
    parser.add_argument('--dpi', type=int, default=100)
    parser.add_argument('--crf', type=int, default=20)
    parser.add_argument('--preset', default='medium')
    parser.add_argument(
        '--ffmpeg', default=None,
        help='ffmpeg executable; auto-detected from PATH when omitted',
    )
    parser.add_argument(
        '--keep_frames', action='store_true',
        help='Keep rendered PNG files next to the video for debugging',
    )
    return parser.parse_args()


def _resolve_project_path(path):
    path = Path(path).expanduser()
    return path if path.is_absolute() else PROJECT_ROOT / path


def _validate_args(args):
    if args.fps <= 0:
        raise ValueError('--fps must be positive')
    if not 0 <= args.score_thresh <= 1:
        raise ValueError('--score_thresh must be in [0, 1]')
    if args.match_radius <= 0:
        raise ValueError('--match_radius must be positive')
    if args.min_box_points < 0 or args.max_points < 0:
        raise ValueError('point counts must be non-negative')
    if args.dpi <= 0:
        raise ValueError('--dpi must be positive')
    if not 0 <= args.crf <= 51:
        raise ValueError('--crf must be in [0, 51]')


def aligned_frame_indices(infos, single_by_frame, four_by_frame):
    """Return dataset order after enforcing exact three-way frame alignment."""

    frame_ids = [str(info.get('token', index)) for index, info in enumerate(infos)]
    if len(frame_ids) != len(set(frame_ids)):
        raise ValueError('Dataset info contains duplicate frame_id values')

    expected = set(frame_ids)
    errors = []
    for name, predictions in (
        ('single-frame', single_by_frame),
        ('four-frame', four_by_frame),
    ):
        actual = set(predictions)
        missing = expected - actual
        extra = actual - expected
        if missing or extra:
            errors.append(
                f'{name}: missing={len(missing)}, extra={len(extra)}'
            )
    if errors:
        raise ValueError('Prediction/info frame mismatch: ' + '; '.join(errors))
    return list(enumerate(frame_ids))


def _resolve_ffmpeg(value):
    if value:
        candidate = Path(value).expanduser()
        if candidate.is_file():
            return str(candidate)
        resolved = shutil.which(value)
        if resolved:
            return resolved
        raise FileNotFoundError(f'ffmpeg executable not found: {value}')
    resolved = shutil.which('ffmpeg')
    if not resolved:
        raise FileNotFoundError('ffmpeg is not on PATH; pass --ffmpeg /path/to/ffmpeg')
    return resolved


def _points_for_display(dataset, dataset_index, maximum):
    points = dataset.get_lidar_with_sweeps(dataset_index, max_sweeps=1)
    pc_range = np.asarray(dataset.point_cloud_range, dtype=np.float32)
    keep = (
        (points[:, 0] >= pc_range[0])
        & (points[:, 0] <= pc_range[3])
        & (points[:, 1] >= pc_range[1])
        & (points[:, 1] <= pc_range[4])
    )
    points = points[keep]
    plotted, _ = _plot_point_subsets(points, points[:0], maximum)
    return points, plotted, pc_range


def render_video_frame(dataset, dataset_index, frame_id, single_anno,
                       four_anno, frame_number, total_frames, args, output_path):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D

    info = dataset.infos[dataset_index]
    current_points, plotted_points, pc_range = _points_for_display(
        dataset, dataset_index, args.max_points,
    )
    manual = _manual_centers_in_range(info, pc_range)
    weak_boxes, pseudo_centers = _weak_overlays(info)
    exhaustive = bool(info.get(
        'center_label_is_exhaustive', info.get('label_is_exhaustive', False),
    ))

    fig, axes = plt.subplots(
        1, 3, figsize=(19.2, 6.4), dpi=args.dpi,
        sharex=True, sharey=True,
    )
    fig.subplots_adjust(left=0.045, right=0.995, bottom=0.09, top=0.80, wspace=0.12)
    label_ax, single_ax, four_ax = axes
    for ax in axes:
        _plot_common_background(ax, plotted_points, pc_range)

    for box in weak_boxes:
        _plot_box(label_ax, box, '#f28e2b', linestyle='--', linewidth=1.4)
    if len(pseudo_centers):
        label_ax.scatter(
            pseudo_centers[:, 0], pseudo_centers[:, 1], marker='+',
            s=55, linewidths=1.5, c='#f28e2b', zorder=6,
        )
    if len(manual):
        label_ax.scatter(
            manual[:, 0], manual[:, 1], marker='x',
            s=72, linewidths=2.0, c='#d62728', zorder=7,
        )

    single_boxes, _, single_supports = _plot_predictions(
        single_ax, current_points, single_anno, args.score_thresh,
        args.min_box_points, '#0072b2',
    )
    four_boxes, _, four_supports = _plot_predictions(
        four_ax, current_points, four_anno, args.score_thresh,
        args.min_box_points, '#cc79a7',
    )
    single_hits = len(greedy_center_matches(
        single_boxes[:, :2], manual, args.match_radius,
    ))
    four_hits = len(greedy_center_matches(
        four_boxes[:, :2], manual, args.match_radius,
    ))

    if exhaustive:
        label_status = 'REVIEWED: center labels approximately complete'
        match_label = 'center hit'
    else:
        label_status = 'INCOMPLETE weak labels: missing annotations expected'
        match_label = 'visible-label match'
    label_ax.set_title(
        f'Ground truth / available labels\n{label_status}\n'
        f'manual={len(manual)}, weak boxes={len(weak_boxes)}, '
        f'other weak centers={len(pseudo_centers)}',
        color='#1b7837' if exhaustive else '#b2182b', fontsize=9,
    )
    single_ax.set_title(
        '1-frame model predictions\n'
        f'boxes={len(single_boxes)}, {match_label}={single_hits}/{len(manual)}, '
        f'low-point={sum(value < args.min_box_points for value in single_supports)}',
        fontsize=9,
    )
    four_ax.set_title(
        '4-frame model predictions\n'
        f'boxes={len(four_boxes)}, {match_label}={four_hits}/{len(manual)}, '
        f'low-point={sum(value < args.min_box_points for value in four_supports)}',
        fontsize=9,
    )

    common_handles = [
        Line2D([], [], marker='^', linestyle='None', color='black', label='LiDAR origin'),
        Line2D([], [], marker='.', linestyle='None', color='0.28', label='current points'),
    ]
    label_ax.legend(handles=common_handles + [
        Line2D([], [], marker='x', linestyle='None', color='#d62728', label='manual center'),
        Line2D([], [], color='#f28e2b', linestyle='--', label='weak 3D box'),
        Line2D([], [], marker='+', linestyle='None', color='#f28e2b', label='other weak center'),
    ], loc='upper right', fontsize=6.2)
    single_ax.legend(handles=common_handles + [
        Line2D([], [], color='#0072b2', label='prediction: score|points'),
        Line2D([], [], color='#0072b2', linestyle=':', label='low point support'),
    ], loc='upper right', fontsize=6.2)
    four_ax.legend(handles=common_handles + [
        Line2D([], [], color='#cc79a7', label='prediction: score|points'),
        Line2D([], [], color='#cc79a7', linestyle=':', label='low point support'),
    ], loc='upper right', fontsize=6.2)

    elapsed = (frame_number - 1) / args.fps
    fig.suptitle(
        f'{frame_id}  |  frame {frame_number}/{total_frames}  |  t={elapsed:.1f}s\n'
        'All panels show the same current-frame points; predictions use 1 and 4 frames.',
        fontsize=11, y=0.96,
    )
    fig.savefig(output_path, facecolor='white')
    plt.close(fig)


def encode_mp4(ffmpeg, frame_dir, output_file, fps, crf, preset):
    command = [
        ffmpeg, '-hide_banner', '-loglevel', 'error', '-y',
        '-framerate', str(fps), '-start_number', '0',
        '-i', str(frame_dir / 'frame_%06d.png'),
        '-c:v', 'libx264', '-preset', preset, '-crf', str(crf),
        '-pix_fmt', 'yuv420p', '-movflags', '+faststart',
        str(output_file),
    ]
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError(
            f'ffmpeg failed with code {result.returncode}: {result.stderr.strip()}'
        )


def main():
    args = parse_args()
    _validate_args(args)

    from simple_det3d.datasets.coda_dataset import CodaDataset
    from simple_det3d.utils.common_utils import create_logger
    from simple_det3d.utils.config import load_config

    cfg_path = _resolve_project_path(args.cfg_file)
    single_path = _resolve_project_path(args.single_predictions)
    four_path = _resolve_project_path(args.four_predictions)
    output_file = _resolve_project_path(args.output_file)
    for path in (cfg_path, single_path, four_path):
        if not path.is_file():
            raise FileNotFoundError(path)
    output_file.parent.mkdir(parents=True, exist_ok=True)
    ffmpeg = _resolve_ffmpeg(args.ffmpeg)

    cfg = load_config(cfg_path)
    if args.root_path is not None:
        cfg.DATA_CONFIG.DATA_PATH = args.root_path
    if args.raw_data_path is not None:
        cfg.DATA_CONFIG.RAW_DATA_PATH = args.raw_data_path
    if args.info_path is not None:
        cfg.DATA_CONFIG.INFO_PATH.test = args.info_path
    root_path = Path(cfg.DATA_CONFIG.DATA_PATH).expanduser()
    if not root_path.is_absolute():
        root_path = PROJECT_ROOT / root_path
    logger = create_logger(output_file.with_suffix('.log'))
    dataset = CodaDataset(
        dataset_cfg=cfg.DATA_CONFIG,
        class_names=cfg.CLASS_NAMES,
        training=False,
        root_path=root_path,
        logger=logger,
    )

    single_by_frame = load_predictions(single_path)
    four_by_frame = load_predictions(four_path)
    aligned = aligned_frame_indices(
        dataset.infos, single_by_frame, four_by_frame,
    )
    if not aligned:
        raise ValueError('No aligned frames found')

    start_time = time.monotonic()
    if args.keep_frames:
        frame_dir = output_file.parent / f'{output_file.stem}_frames'
        frame_dir.mkdir(parents=True, exist_ok=True)
        context = None
    else:
        context = tempfile.TemporaryDirectory(prefix='wheelchair_video_frames_')
        frame_dir = Path(context.name)
    try:
        for output_index, (dataset_index, frame_id) in enumerate(
            tqdm(aligned, desc='render video frames'),
        ):
            render_video_frame(
                dataset, dataset_index, frame_id,
                single_by_frame[frame_id], four_by_frame[frame_id],
                output_index + 1, len(aligned), args,
                frame_dir / f'frame_{output_index:06d}.png',
            )
        encode_mp4(
            ffmpeg, frame_dir, output_file,
            args.fps, args.crf, args.preset,
        )
    finally:
        if context is not None:
            context.cleanup()

    exhaustive_frames = sum(bool(info.get(
        'center_label_is_exhaustive', info.get('label_is_exhaustive', False),
    )) for info in dataset.infos)
    summary = {
        'output_file': str(output_file),
        'config': str(cfg_path),
        'single_predictions': str(single_path),
        'four_predictions': str(four_path),
        'frame_count': len(aligned),
        'fps': args.fps,
        'duration_seconds': len(aligned) / args.fps,
        'reviewed_exhaustive_frames': exhaustive_frames,
        'incomplete_weak_label_frames': len(aligned) - exhaustive_frames,
        'score_thresh': args.score_thresh,
        'match_radius': args.match_radius,
        'render_seconds': time.monotonic() - start_time,
        'resolution': [int(19.2 * args.dpi), int(6.4 * args.dpi)],
        'frames_kept': args.keep_frames,
    }
    summary_path = output_file.with_suffix('.json')
    summary_path.write_text(
        json.dumps(summary, ensure_ascii=False, indent=2), encoding='utf-8',
    )
    logger.info(
        'Created %s: %d frames, %.1f seconds at %.3g FPS',
        output_file, len(aligned), len(aligned) / args.fps, args.fps,
    )
    print(f'Video: {output_file}')
    print(f'Summary: {summary_path}')


if __name__ == '__main__':
    main()
