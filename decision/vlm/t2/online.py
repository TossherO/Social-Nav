LABELS = string.ascii_uppercase + string.ascii_lowercase


def _image(payload, *, jpeg_quality=None):
    if not isinstance(payload,(bytes,Image.Image)):
        raise ValueError('Expected a PNG or an RGB canvas')
    if jpeg_quality is not None:
        if type(jpeg_quality) is not int or not 1<=jpeg_quality<=95:
            raise ValueError('JPEG quality must be an integer between 1 and 95')
        image=payload if isinstance(payload,Image.Image) else Image.open(io.BytesIO(payload)).convert('RGB')
        out=io.BytesIO();image.save(out,format='JPEG',quality=jpeg_quality,subsampling=0,optimize=True)
        payload=out.getvalue()
    elif isinstance(payload,Image.Image):
        out=io.BytesIO()
        payload.save(out,format='PNG')
        payload=out.getvalue()
    mime='image/png' if jpeg_quality is None else 'image/jpeg'
    return dict(type='image_url', image_url=dict(
        url='data:'+mime+';base64,' + base64.b64encode(payload).decode('ascii')))

def _draw_search(image, window, choices, *, return_canvas=False):
    from ..scene_inputs import bev_xy, BEV_RECT, BEV_SIZE, font
    scene=window.get('scene') or {}
    world=np.asarray((scene.get('localization') or {}).get('world_from_lidar'),dtype=float)
    prior=np.asarray((scene.get('prior') or {}).get('map_from_local'),dtype=float)
    if world.shape!=(4,4) or prior.shape!=(4,4) or not np.isfinite(world).all() or not np.isfinite(prior).all():
        if any(v['kind']=='observation' and v['candidate']['kind']!='wait' for v in choices.values()):
            raise ValueError('Map-to-LiDAR transform required for search display')
        inverse=None
    else:
        transform=prior@world
        yaw=math.atan2(transform[1,0],transform[0,0])
        c,s=math.cos(yaw),math.sin(yaw)
        inverse=np.array([[c,s],[-s,c]])
        origin=transform[:2,3]
    extent=window['fields']['e']
    canvas=image.copy() if isinstance(image,Image.Image) else Image.open(io.BytesIO(image)).convert('RGB')
    separate=window.get('image_mode')=='raw_rgb_with_separate_bev'
    if separate and canvas.size!=BEV_SIZE:raise ValueError('Separate BEV size is invalid')
    def image_xy(x,y):
        px,py=bev_xy(x,y,extent)
        return (px-BEV_RECT[0],py-BEV_RECT[1]) if separate else (px,py)
    draw=ImageDraw.Draw(canvas)
    for label,value in choices.items():
        if value['kind']!='observation':continue
        candidate=value['candidate'];pose=candidate.get('pose')
        if candidate['kind']=='wait':
            x,y=0.,0.
        else:
            if not isinstance(pose,(list,tuple)) or len(pose)!=3 or not all(math.isfinite(v) for v in pose):
                raise ValueError('Search pose is invalid')
            x,y=map(float,inverse@(np.asarray(pose[:2])-origin))
        px,py=image_xy(x,y)
        # Keep an out-of-view option visible at the edge without representing it
        # as a measured location; its actual pose remains in the text.
        outside=not (extent[0]<=x<=extent[1] and extent[2]<=y<=extent[3])
        left,top,right,bottom=(0,0,*BEV_SIZE) if separate else BEV_RECT
        px=max(left+15,min(right-15,px))
        py=max(top+15,min(bottom-15,py))
        draw.rectangle((px-11,py-11,px+11,py+11),fill='#173b4d',outline='#ffe474',width=2)
        draw.text((px-6,py-10),label,fill='white',font=font(16))
        if candidate['kind']!='wait' and not outside:
            direction=inverse@np.array([math.cos(pose[2]),math.sin(pose[2])])
            tip=image_xy(x+.4*direction[0],y+.4*direction[1])
            draw.line((px,py,*tip),fill='#ffe474',width=3)
            draw.ellipse((tip[0]-3,tip[1]-3,tip[0]+3,tip[1]+3),fill='#ffe474')
        if outside:draw.text((px+10,py-10),'out',fill='#b02a28',font=font(14))
    if return_canvas:return canvas
    out=io.BytesIO();canvas.save(out,format='PNG');return out.getvalue()


def prepare(window, images, description, search, *, reference_image=None, reference=None, task=None, jpeg_quality=None):
    """Freeze candidate mapping to the source window and search set.

    Search candidates are already generated by navigation and are hypotheses,
    not permission to move. The caller must recheck them against the current scene.
    """
    if (not isinstance(window, dict) or window.get('input_fingerprint') !=
            digest({k:v for k,v in window.items() if k != 'input_fingerprint'})):
        raise ValueError('Invalid source window')
    raw=window.get('image_mode')=='raw_rgb_with_separate_bev'
    image_count=6 if raw else 3
    if (not isinstance(description,str) or not description.strip() or
            not isinstance(images,(tuple,list)) or len(images)!=image_count or len(window.get('images',[]))!=image_count):
        raise ValueError('T2 requires a description and three causal images')
    for image,spec in zip(images,window['images']):
        if spec.get('encoding')=='rgb_pixels':
            pixels=(image.tobytes() if isinstance(image,Image.Image) and image.mode=='RGB' and
                    list(image.size)==spec.get('size') else None)
        else:
            pixels=image if isinstance(image,bytes) else None
        if pixels is None or hashlib.sha256(pixels).hexdigest()!=spec.get('sha256'):
            raise ValueError('Image differs from source window')
    if (not isinstance(search,dict) or search.get('binding') !=
            fingerprint({k:v for k,v in search.items() if k!='binding'}) or
            search.get('clock_domain') != window.get('clock_domain') or
            search.get('source_stamp_s') != window.get('stamp_s') or
            search.get('scene_binding', (window.get('scene') or {}).get('input_fingerprint')) !=
            (window.get('scene') or {}).get('input_fingerprint')):
        raise ValueError('Search candidates must bind the same source observation')
    options=search.get('candidates')
    if (not isinstance(options,list) or not options or
            not any(v.get('kind')=='wait' for v in options) or
            any(type(v.get('id')) is not int for v in options) or
            len({v['id'] for v in options})!=len(options)):
        raise ValueError('Search requires distinct candidates including wait')
    ids=window.get('pid_to_track')
    if (not isinstance(ids,dict) or sorted(map(int,ids))!=window['fields']['v'] or
            len(options)>len(LABELS)):
        raise ValueError('Invalid or excessive T2 candidates')
    choices={}
    source=window.get('scene') or {}
    people=(source.get('people') or {}).get('data') or {}
    from navigation.planning.people import stable_identity
    tracks={stable_identity(people,t):t for t in people.get('tracks',[])}
    observations={row[0]:row for row in window['fields']['o']}
    for pid in sorted(map(int,ids)):
        identity=ids[str(pid)];track=tracks.get(tuple(identity));row=observations.get(pid)
        # A predicted point without an associated RGB person cannot establish
        # visual identity, even though it remains visible on the BEV.
        if (not track or track.get('state')!='observed' or not track.get('confirmed') or
                not row or (not raw and not row[2][-1])):
            continue
        choices['P'+str(pid)]=dict(kind='person',pid=pid,identity=copy.deepcopy(identity),
            lifecycle_generation=track['lifecycle_generation'])
    for index,option in enumerate(options):
        choices[LABELS[index]]=dict(kind='observation',candidate=copy.deepcopy(option))
    user=dict(target_description=description.strip(),people=[label
        for label,value in choices.items() if value['kind']=='person'],
        observation_options={label:value['candidate'] for label,value in choices.items()
                             if value['kind']=='observation'},
        observation_fields=window['fields'])
    content=[]
    if reference_image is not None or reference is not None:
        if (not isinstance(reference_image,bytes) or not isinstance(reference,dict) or
                reference.get('reference_id')!=fingerprint({k:v for k,v in reference.items() if k!='reference_id'}) or
                reference.get('crop_sha256')!=hashlib.sha256(reference_image).hexdigest() or
                reference.get('description')!=description.strip() or
                reference.get('clock_domain')!=window['clock_domain'] or
                type(reference.get('rgb_stamp_s')) not in (int,float) or
                rgb_age_s(window['stamp_s'],reference['rgb_stamp_s'],source.get('stamp_ns'),reference.get('rgb_stamp_ns'))<0):
            raise ValueError('Reference image does not match its causal metadata')
        content.extend([dict(type='text',text='Fixed target reference'),_image(reference_image,jpeg_quality=jpeg_quality)])
    images=list(images)
    images[-1]=_draw_search(images[-1],window,choices,return_canvas=True)
    for i,image in enumerate(images):
        label=('Observation '+str(i//2)+(' raw RGB' if i%2==0 else ' independent LiDAR BEV')) if raw else 'Observation '+str(i)
        content.extend([dict(type='text',text=label),_image(image,jpeg_quality=jpeg_quality)])
    content.append(dict(type='text',text=json.dumps(user,ensure_ascii=False,separators=(',',':'))))
    config=load_config()
    prompt_path=config['tasks']['follow']['raw_rgb_prompt' if raw else 'prompt']
    prompt=project_path(prompt_path).read_text(encoding='utf-8').rstrip('\n')
    body=dict(model=config['model']['served_name'],
        messages=[dict(role='system',content=prompt),dict(role='user',content=content)],
        chat_template_kwargs=dict(enable_thinking=False),temperature=0,max_tokens=24,
        regex=selection_regex(choices),stream=True,stream_options=dict(include_usage=True))
    prepared=dict(window_binding=window['input_fingerprint'],search_binding=search['binding'],
        source_stamp_s=window['stamp_s'],clock_domain=window['clock_domain'],
        scene_binding=(window.get('scene') or {}).get('input_fingerprint'),
        reference_id=None if reference is None else reference['reference_id'],task=copy.deepcopy(task),
        choices=choices,body=body)
    prepared['binding']=fingerprint(prepared)
    return prepared


def _infer(prepared, *, client_factory=None, backend='dspark', private_config=None, budget_factory=None):
    if prepared.get('binding')!=fingerprint({k:v for k,v in prepared.items() if k!='binding'}):
        raise ValueError('T2 request changed')
    if backend=='dspark':
        result=request_dspark(prepared['body'],client_factory=client_factory,timeout_s=5)
        result['backend']='dspark'
    elif backend=='hosted':
        from .hosted import request_hosted
        options={}
        if private_config is not None:options['private_config']=private_config
        if budget_factory is not None:options['budget_factory']=budget_factory
        result=request_hosted(prepared['body'],client_factory=client_factory,timeout_s=5,**options)
    else:raise ValueError('Unknown T2 backend')
    result.update(request_binding=prepared['binding'])
    if result['status']=='complete':
        try:selection=parse_selection(result['raw_content'],prepared['choices'])
        except ValueError:result.update(status='unavailable',reason='invalid_t2_response')
        else:
            result['selection']=selection
            result['choice']=copy.deepcopy(prepared['choices'][selection])
    return result


def selected_reference(prepared, result, window, *, task_id, revision, goal_id):
    """Build a reference for the selected source track; the controller rechecks history."""
    if (prepared.get('binding')!=fingerprint({k:v for k,v in prepared.items() if k!='binding'}) or
            result.get('request_binding')!=prepared['binding'] or result.get('status')!='complete' or
            parse_selection(result.get('raw_content'),prepared['choices'])!=result.get('selection') or
            prepared['choices'].get(result.get('selection'))!=result.get('choice') or
            window.get('input_fingerprint')!=prepared['window_binding'] or
            digest({k:v for k,v in window.items() if k!='input_fingerprint'})!=window['input_fingerprint']):
        raise ValueError('Unbound T2 result or observation')
    choice=result['choice']
    if choice['kind']!='person':raise ValueError('T2 did not select a person')
    scene=window['scene'];people=scene['people']['data']
    from navigation.planning.people import stable_identity
    track=next((t for t in people['tracks'] if list(stable_identity(people,t))==choice['identity']),None)
    rgb_ns=window['sources'][-1]['rgb_input']['rgb_stamp_ns']
    rgb=rgb_ns/1_000_000_000
    if (track is None or track['state']!='observed' or not track['confirmed'] or
            track['lifecycle_generation']!=choice['lifecycle_generation'] or
            track['last_observed_stamp_s']!=people['stamp_s'] or
            not 0<=rgb_age_s(scene['as_of'],rgb,scene.get('stamp_ns'),rgb_ns)<=.15):
        raise ValueError('T2 person lacks same-source observation')
    ref=dict(task_id=task_id,task_revision=revision,goal_id=goal_id,
        scene_binding=scene['input_fingerprint'],stamp_s=scene['as_of'],rgb_stamp_s=rgb,rgb_stamp_ns=rgb_ns,
        clock_domain=scene['clock_domain'],
        local_identity=[scene[k] for k in ('session_id','generation','frame_id')],
        track=dict(identity=choice['identity'],lifecycle_generation=choice['lifecycle_generation'],
            people_fingerprint=people['input_fingerprint'],people_stamp_s=people['stamp_s'],
            support_stamp_s=track['last_observed_stamp_s']),
        t2_request_binding=prepared['binding'],t2_response=result['raw_content'])
    ref['reference_id']=fingerprint(ref)
    return ref


class FollowRequest:
    """One in-flight source-bound T2 request, with no implicit retry."""
    def __init__(self, prepared):
        self.prepared=copy.deepcopy(prepared)
        self.binding=prepared['binding']
        self.attempted=False
        self.result=None

    def infer(self, *, client_factory=None, backend='dspark', private_config=None, budget_factory=None):
        if self.attempted:raise ValueError('T2 request already attempted')
        self.attempted=True
        self.result=_infer(self.prepared,client_factory=client_factory,backend=backend,
                           private_config=private_config,budget_factory=budget_factory)
        return copy.deepcopy(self.result)

    def accept(self, result):
        if self.result is None or result!=self.result or result.get('status')!='complete':
            raise ValueError('A complete, unchanged T2 response is required')
        self.result=None
        return copy.deepcopy(result['choice'])
